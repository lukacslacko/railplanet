import assert from 'node:assert/strict';
import {planRoute,evaluate,speedLimit,area,DEFAULTS,R,distance,unit} from '../dist/rail.js';
import {rotate,axisAngle} from '../dist/orbit.js';
const point=(x,y=0)=>[Math.cos(x/R)*Math.cos(y/R),Math.sin(y/R),Math.sin(x/R)*Math.cos(y/R)];
const coordinate=n=>[Math.atan2(n[2],n[0])*R,Math.asin(n[1])*R];
const flat=()=>({height:0,land:true}),start=point(0),end=point(7800);
let result=await planRoute(start,end,flat);
assert(!result.error,result.error);assert(Math.abs(result.length-7800)<.1,'flat terrain should give an almost direct railway');
assert(distance(result.points[0].n,start)<.001&&distance(result.points.at(-1).n,end)<.001,'railway endpoints must match the selected locations');
assert(result.points[0].speed===0&&result.points.at(-1).speed===0,'journey time includes station stops');
for(let i=1;i<result.points.length;i++){
 const a=result.points[i-1],b=result.points[i],d=distance(a.n,b.n);
 assert(b.speed*b.speed<=a.speed*a.speed+2*.55*d+.001,'acceleration envelope');
 assert(a.speed*a.speed<=b.speed*b.speed+2*.7*d+.001,'braking envelope');
}
const q=axisAngle([.2,1,.6],2.1),rotated=result.points.map(p=>({...p,n:rotate(q,p.n)}));
const polar=evaluate(rotated,flat,DEFAULTS);assert(polar&&Math.abs(polar.length-result.length)<.001,'metric and curvature must be rotation invariant');
const lake=n=>{const[x,y]=coordinate(n);return {height:0,land:Math.hypot(x-3900,y)>1000};};
result=await planRoute(start,end,lake);
assert(!result.error,result.error);assert(result.length>8000&&result.length<11000,'route should detour around the lake');
assert(result.points.every(p=>lake(p.n).land),'no route samples may cross a lake');
assert(result.minRadius>=DEFAULTS.minRadius-.05,'horizontal curve limit');
const ridge=n=>{const[x,y]=coordinate(n);return {land:true,height:250*Math.exp(-(((x-3900)/850)**2))*(1-.85*Math.exp(-(((y-2300)/650)**2)))};};
result=await planRoute(start,end,ridge);
assert(!result.error,result.error);assert(Math.max(...result.points.map(p=>coordinate(p.n)[1]))>1500,'search must discover the mountain pass');
assert(result.maxGrade<=DEFAULTS.maxGrade+.000001,'grade limit');assert(result.maxWork<=DEFAULTS.maxEarthwork+.1,'earthwork depth limit');
assert(result.maxWork<20,'a pass should be preferred over large excavations');
assert(speedLimit(.03,0,DEFAULTS)<speedLimit(0,0,DEFAULTS),'grades reduce maximum speed');
assert(speedLimit(0,1/300,DEFAULTS)<speedLimit(0,1/1200,DEFAULTS),'tight curves reduce maximum speed');
const filled=[{n:point(0),h:2},{n:point(1000),h:2}],a=evaluate(filled,flat,DEFAULTS),b=evaluate(filled,flat,{...DEFAULTS,earthworkCost:.05});
assert(a&&b&&a.volume>0);assert(area(0,.5)>area(0,0),'cross-slope formation grading must have an earthwork cost');assert(Math.abs((b.score-a.score)-.025*a.volume)<.01,'earthwork cost must be proportional to volume');
assert(!evaluate([{n:point(0),h:0},{n:point(100),h:30}],flat,DEFAULTS),'steep railway must be rejected');
assert(!evaluate([{n:point(0),h:0},{n:point(100),h:0},{n:point(100,100),h:0}],flat,DEFAULTS),'sharp corners must be rejected');
const loop=Array.from({length:97},(_,i)=>({n:point(500*Math.sin(i*2*Math.PI/96),500*(1-Math.cos(i*2*Math.PI/96))),h:0}));
assert(!evaluate(loop,flat,DEFAULTS),'unsupported self-crossing or overlapping track must be rejected');
assert((await planRoute(start,end,()=>({height:0,land:false}))).error,'water endpoints must be rejected');
const seam=await planRoute(unit([-1,0,.015]),unit([-1,0,-.015]),flat);
assert(!seam.error&&seam.length<2500,'short route must cross the longitude seam without a world-sized detour');
await assert.rejects(()=>planRoute(start,end,lake,{}, {cancelled:()=>true}),/cancelled/,'search cancellation must interrupt the worker loop');
console.log('Railways verified: direct routes, lake avoidance, pass discovery, rotation/seam continuity, exact endpoints, grade/curvature limits, earthwork costs, speed/acceleration envelopes, and cancellation.');
